#!/usr/bin/env bash
# Publish a report: check it, copy its site/ to $WWW_ROOT/<slug>/, rebuild the reports index
# ($WWW_ROOT/index.html) and print the public URL. Re-run it after editing a report.
#
#   publish.sh <slug>
#   publish.sh --index      only rebuild the index (e.g. after removing a report folder)
set -euo pipefail

skill_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
reports="${REPORTS_HOME:-$HOME/reports}"
www="${WWW_ROOT:-$HOME/www}"
marker="generated by create-report"

die() { echo "publish: $*" >&2; exit 1; }
problems=()
problem() { problems+=("$*"); }

build_index() {
  local index="$www/index.html" d name lines others cards other count tmp
  mkdir -p "$www"
  if [ -f "$index" ] && ! grep -q "$marker" "$index"; then
    die "$index exists and was not generated by create-report; move it aside, then run: publish.sh --index"
  fi

  lines=""
  others=""
  for d in "$www"/*; do
    name=${d##*/}
    [ "$name" = "index.html" ] && continue
    [ -e "$d" ] || continue
    if [ -f "$d/report.json" ] && jq -e 'type == "object"' "$d/report.json" >/dev/null 2>&1; then
      lines+="$(jq -c --arg dir "$name" '. + {dir: $dir}' "$d/report.json")"$'\n'
    elif [ -d "$d" ]; then
      others+="$name/"$'\n'
    else
      others+="$name"$'\n'
    fi
  done

  cards=$(printf '%s' "$lines" | jq -rs '
    sort_by(.date // "", .created // "", .dir) | reverse | map(
      "      <li><a class=\"card\" href=\"\(.dir | @uri)/\" data-theme=\"\(.theme // "" | @html)\">"
      + "<time datetime=\"\(.date // "" | @html)\">\(.date // "" | @html)"
      + (if (.updated // "") != "" then " · updated \(.updated | @html)" else "" end) + "</time>"
      + "<h2>\(.title // .dir | @html)</h2>"
      + (if (.tldr // "") != "" then "<p>\(.tldr | @html)</p>" else "" end)
      + (if ((.tags // []) | length) > 0 then "<ul class=\"tags\">" + ((.tags | map("<li>\(@html)</li>")) | join("")) + "</ul>" else "" end)
      + "</a></li>"
    ) | if length == 0 then "      <li class=\"empty\">No reports yet.</li>" else join("\n") end')
  count=$(printf '%s' "$lines" | jq -rs 'length | if . == 1 then "1 report" else "\(.) reports" end')
  other=$(printf '%s' "$others" | jq -Rrs '
    split("\n") | map(select(length > 0)) |
    if length == 0 then "" else
      "    <section class=\"other\"><h2>Other files</h2><ul>"
      + (map("<li><a href=\"\(rtrimstr("/") | @uri)\(if endswith("/") then "/" else "" end)\">\(@html)</a></li>") | join(""))
      + "</ul></section>"
    end')

  tmp="$index.tmp.$$"
  jq -Rrs --arg cards "$cards" --arg other "$other" --arg count "$count" \
    'gsub("\\{\\{CARDS\\}\\}"; $cards) | gsub("\\{\\{OTHER\\}\\}"; $other) | gsub("\\{\\{COUNT\\}\\}"; $count)' \
    "$skill_dir/assets/site-index.html" >"$tmp"
  mv "$tmp" "$index"
}

public_url() {
  local path=$1 domain=${WWW_DOMAIN:-}
  domain=${domain#http://}
  domain=${domain#https://}
  domain=${domain%/}
  if [ -n "$domain" ]; then
    echo "https://$domain/$path"
  else
    echo "http://localhost:${WEB_PORT:-8080}/$path"
    echo "publish: note: WWW_DOMAIN is not set, so this is the in-box address; set it in .env to get public links" >&2
  fi
}

command -v jq >/dev/null || die "jq is required"

if [ "${1:-}" = "--index" ]; then
  build_index
  echo "index: $www/index.html"
  public_url ""
  exit 0
fi

slug=${1:-}
[ -n "$slug" ] || die "usage: publish.sh <slug> | --index"
# The slug names the folder this script replaces under $WWW_ROOT: keep it to what new-report.sh makes.
[[ "$slug" =~ ^[0-9]{4}-[0-9]{2}-[0-9]{2}-[a-z0-9-]+$ ]] || die "'$slug' is not a report slug (YYYY-MM-DD-name)"
ws="$reports/$slug"
site="$ws/site"
[ -d "$site" ] || die "no report at $site"

# ---- Checks: refuse to publish an unfinished or leaky report ----
[ -f "$site/index.html" ] || problem "site/index.html is missing"
if [ -f "$site/report.json" ]; then
  for f in title date tldr model; do
    jq -e --arg f "$f" '(.[$f] // "") | tostring | length > 0' "$site/report.json" >/dev/null 2>&1 \
      || problem "report.json: \"$f\" is empty"
  done
else
  problem "site/report.json is missing"
fi

if [ -f "$site/index.html" ]; then
  grep -q '{{' "$site/index.html" && problem "index.html still has {{placeholders}}"
  for leftover in 'One sentence that frames' 'The answer, in one or two sentences' 'src-example' 'Supporting point.'; do
    grep -qF "$leftover" "$site/index.html" && problem "index.html still has template text: \"$leftover\""
  done
  grep -q 'class="tldr' "$site/index.html" || problem "index.html has no TL;DR section (class=\"tldr\")"

  # Every citation must point at a source in the list.
  cited=$(grep -oE 'class="cite"[^>]*href="#[^"]+"|href="#[^"]+"[^>]*class="cite"' "$site/index.html" | grep -oE 'href="#[^"]+"' | sed -E 's/href="#([^"]+)"/\1/' | sort -u || true)
  for id in $cited; do
    grep -qE "id=\"$id\"" "$site/index.html" || problem "citation #$id has no matching source <li id=\"$id\">"
  done

  if grep -qE 'class="([^"]* )?mermaid( [^"]*)?"' "$site/index.html" && [ ! -s "$site/assets/vendor/mermaid.min.js" ]; then
    problem "uses Mermaid but assets/vendor/mermaid.min.js is missing (bash $skill_dir/scripts/new-report.sh --vendor $slug)"
  fi
  if grep -qE 'class="([^"]* )?chart( [^"]*)?"' "$site/index.html" && [ ! -s "$site/assets/vendor/chart.umd.min.js" ]; then
    problem "uses charts but assets/vendor/chart.umd.min.js is missing (bash $skill_dir/scripts/new-report.sh --vendor $slug)"
  fi
fi

# The prompt stays private.
if [ -n "$(find "$site" -iname 'prompt*' -print -quit)" ]; then
  problem "site/ contains a prompt file; prompts never get published"
fi
if [ ! -f "$ws/prompt.md" ] || grep -q 'create-report: replace this line' "$ws/prompt.md"; then
  problem "$ws/prompt.md does not have the user's request yet (it stays private, but it must be saved)"
fi

if [ "${#problems[@]}" -gt 0 ]; then
  echo "publish: not published, fix these first:" >&2
  printf '  - %s\n' "${problems[@]}" >&2
  exit 1
fi

# ---- Copy ----
dest="$www/$slug"
today=$(date +%F)
if [ -d "$dest" ] && [ "$(jq -r '.date' "$site/report.json")" != "$today" ]; then
  # Republishing an older report: stamp it as updated.
  tmp="$site/report.json.tmp"
  jq --arg d "$today" '.updated = $d' "$site/report.json" >"$tmp" && mv "$tmp" "$site/report.json"
fi

mkdir -p "$www"
rm -rf "$dest.publishing"
cp -R "$site" "$dest.publishing"
# Ship only the libraries the page uses (Mermaid alone is ~3.5 MB).
grep -qE 'class="([^"]* )?mermaid( [^"]*)?"' "$site/index.html" || rm -f "$dest.publishing/assets/vendor/mermaid.min.js"
grep -qE 'class="([^"]* )?chart( [^"]*)?"' "$site/index.html" || rm -f "$dest.publishing/assets/vendor/chart.umd.min.js"
rm -rf "$dest"
mv "$dest.publishing" "$dest"

build_index
echo "published: $dest"
public_url "$slug/"
